package domain

import (
	"encoding/json"
	"time"
)

// JobDescription represents a job requisition uploaded or generated.
type JobDescription struct {
	ID                  string           `json:"id"`
	UploadedByID        string           `json:"uploaded_by"`
	Source              JdSource         `json:"source"`
	OriginalFilename    string           `json:"original_filename"`
	FilePath            *string          `json:"file_path,omitempty"`
	FileType            *FileType        `json:"file_type,omitempty"`
	RawText             *string          `json:"raw_text,omitempty"`
	ParseStatus         ParseStatus      `json:"parse_status"`
	GenerationStatus    GenerationStatus `json:"generation_status"`
	GenerationInputJSON json.RawMessage  `json:"generation_input_json,omitempty"`
	CreatedAt           time.Time        `json:"created_at"`
	UpdatedAt           time.Time        `json:"updated_at"`
	DeletedAt           *time.Time       `json:"deleted_at,omitempty"`

	// Relational fields
	ExtractedData *JdExtractedData `json:"extracted_data,omitempty"`
	Tests         []Test           `json:"tests,omitempty"`
}

// JdExtractedData contains parsed skills and taxonomy generated by LLM analysis.
type JdExtractedData struct {
	ID                     string          `json:"id"`
	JdID                   string          `json:"jd_id"`
	JobTitle               *string         `json:"job_title,omitempty"`
	SeniorityLevel         *string         `json:"seniority_level,omitempty"`
	MustHaveSkills         json.RawMessage `json:"must_have_skills"`
	NiceToHaveSkills       json.RawMessage `json:"nice_to_have_skills"`
	ToolsTechnologies      json.RawMessage `json:"tools_technologies"`
	Responsibilities       json.RawMessage `json:"responsibilities"`
	RecommendedTestTopics  json.RawMessage `json:"recommended_test_topics"`
	DifficultyDistribution json.RawMessage `json:"difficulty_distribution"`
	ExtractedAt            time.Time       `json:"extracted_at"`
}
