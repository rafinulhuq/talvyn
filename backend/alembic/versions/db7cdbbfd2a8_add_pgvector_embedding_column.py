depends_on: Union[str, Sequence[str], None] = None

EMBEDDING_DIM = 768  # nomic-embed-text output size


def upgrade() -> None:
    op.execute("CREATE EXTENSION IF NOT EXISTS vector;")

    # The initial_schema migration uses current ORM metadata and may already
    # create this column on a brand-new database. Keep this migration safe for
    # both fresh CI databases and older upgraded databases.
    op.execute(
        f"ALTER TABLE evaluations "
        f"ADD COLUMN IF NOT EXISTS embedding vector({EMBEDDING_DIM});"
    )

    # HNSW index for fast approximate cosine-similarity search. Cheap to
    # build even when empty; pgvector adds rows to it as embeddings land.
    op.execute(
        "CREATE INDEX IF NOT EXISTS ix_evaluations_embedding_hnsw "
        "ON evaluations USING hnsw (embedding vector_cosine_ops);"
    )


