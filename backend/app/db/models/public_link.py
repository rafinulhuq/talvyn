"""
SQLAlchemy ORM model for public assessment links.

A PublicAssessmentLink lets an admin share one URL for a JD's approved
tests with any number of candidates. The link itself only identifies the
assessment (JD + approved tests) — it never grants access to a specific
candidate's attempt. Each candidate who registers through it gets their
own private Invitation with its own hashed magic-link token, created via
the same invitation_service helpers used by the manual invite flow.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, Enum, ForeignKey, Index, Integer, String, func
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base
from app.db.models._types import GUID
from app.db.models.enums import PublicLinkStatus


class PublicAssessmentLink(Base):
    __tablename__ = "public_assessment_links"
    __table_args__ = (
        Index("ix_public_links_jd_id", "jd_id"),
    )

    id: Mapped[str] = mapped_column(
        GUID(), primary_key=True, default=lambda: str(uuid.uuid4())
    )
    jd_id: Mapped[str] = mapped_column(
        GUID(), ForeignKey("job_descriptions.id", ondelete="CASCADE"), nullable=False
    )
    # Public, unguessable identifier used directly in the shareable URL —
    # unlike invitation tokens this is not secret, so it is stored as-is
    # rather than hashed.
    public_slug: Mapped[str] = mapped_column(String(43), unique=True, nullable=False)
    title: Mapped[str | None] = mapped_column(String(255), nullable=True)
    status: Mapped[PublicLinkStatus] = mapped_column(
        Enum(PublicLinkStatus, name="PublicLinkStatus", create_type=False),
        nullable=False,
        default=PublicLinkStatus.ACTIVE,
        server_default=PublicLinkStatus.ACTIVE.value,
    )
    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    max_registrations: Mapped[int | None] = mapped_column(Integer, nullable=True)
    registration_count: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )
    # Every resolved page load that finds this link (regardless of whether it
    # turned out usable) — the top of the funnel. Incremented in
    # resolve_public_link(), never in register_via_public_link(), so a
    # registration submit doesn't double-count the view the candidate already
    # generated by loading the page first.
    view_count: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )
    created_by: Mapped[str | None] = mapped_column(
        GUID(), ForeignKey("users.id"), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    def __repr__(self) -> str:
        return (
            f"<PublicAssessmentLink id={self.id!r} "
            f"jd_id={self.jd_id!r} status={self.status!r}>"
        )
